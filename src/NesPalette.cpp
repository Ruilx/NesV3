#include "NesPalette.h"

namespace {
QColor rgb(int red, int green, int blue) {
    return QColor(red, green, blue);
}
}

NesPalette::NesPalette()
    : paletteColors(standard2C02GUPalette()) {
}

NesPalette::NesPalette(const QVector<QColor> &colors)
    : paletteColors(colors) {
    if (this->paletteColors.size() != ColorCount) {
        this->paletteColors = standard2C02GUPalette();
    }
}

const QVector<QColor> &NesPalette::colors() const {
    return this->paletteColors;
}

QColor NesPalette::colorAt(int index) const {
    return this->paletteColors.value(index, Qt::black);
}

void NesPalette::setColor(int index, const QColor &color) {
    if (index < 0 || index >= ColorCount || !color.isValid()) {
        return;
    }

    this->paletteColors[index] = color;
}

